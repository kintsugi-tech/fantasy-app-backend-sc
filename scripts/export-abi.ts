/**
 * Exports what the off-chain app needs from this repo into
 * injective-m2-frontend/packages/chain/src/generated (override with M2_EXPORT_DIR):
 *
 *   abis.ts          typed ABIs (`as const`, so viem infers every call)
 *   addresses.ts     deployed addresses per chainId, from Ignition journals
 *   m2-encoding.ts   the reference encoding library (scripts/lib/m2.ts)
 *   m2-vectors.json  the shared encoding vectors
 *
 *   pnpm export-abi
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import hre from 'hardhat'

const root = fileURLToPath(new URL('..', import.meta.url))
const outDir = path.resolve(
  process.env.M2_EXPORT_DIR ?? path.join(root, '../injective-m2-frontend/packages/chain/src/generated'),
)
const HEADER = '// Generated by injective-m2-backend/scripts/export-abi.ts. Do not edit.\n\n'

const contracts = {
  ResultsRegistry: 'resultsRegistryAbi',
  Predictions: 'predictionsAbi',
} as const
const chains = { injectiveTestnet: 1439, injectiveMainnet: 1776 } as const

mkdirSync(outDir, { recursive: true })

let abis = HEADER
for (const [name, exportName] of Object.entries(contracts)) {
  const artifact = await hre.artifacts.readArtifact(name)
  abis += `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n\n`
}
writeFileSync(path.join(outDir, 'abis.ts'), abis)

const addresses: Record<number, Record<string, string>> = {}
for (const chainId of Object.values(chains)) {
  const file = path.join(root, `ignition/deployments/chain-${chainId}/deployed_addresses.json`)
  if (!existsSync(file)) continue
  const deployed = JSON.parse(readFileSync(file, 'utf8')) as Record<string, string>
  addresses[chainId] = Object.fromEntries(
    Object.keys(contracts).map((name) => [name, deployed[`M2#${name}`]]),
  )
}
writeFileSync(
  path.join(outDir, 'addresses.ts'),
  `${HEADER}export const m2Addresses = ${JSON.stringify(addresses, null, 2)} as const\n`,
)

writeFileSync(
  path.join(outDir, 'm2-encoding.ts'),
  HEADER + readFileSync(path.join(root, 'scripts/lib/m2.ts'), 'utf8'),
)
copyFileSync(path.join(root, 'test/vectors/m2-vectors.json'), path.join(outDir, 'm2-vectors.json'))

console.log(`exported ABIs, addresses (${Object.keys(addresses).join(', ') || 'none deployed'}) to ${outDir}`)
